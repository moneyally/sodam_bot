@test
async def translate_rules():
    assert translate("SELECT * FROM t WHERE a=?") == "SELECT * FROM t WHERE a=%s"
    assert translate("INSERT OR IGNORE INTO t VALUES(?,?)").endswith("ON CONFLICT DO NOTHING")
    assert "GENERATED BY DEFAULT AS IDENTITY" in translate("CREATE TABLE t(id INTEGER PRIMARY KEY AUTOINCREMENT)")
    assert "AUTOINCREMENT" not in translate("CREATE TABLE t(id INTEGER PRIMARY KEY AUTOINCREMENT)")
    assert "extract(epoch from now())" in translate("INSERT INTO t(ts) VALUES(strftime('%s','now'))")
    assert translate("SELECT x FROM t WHERE b LIKE '%a%'") == "SELECT x FROM t WHERE b LIKE '%%a%%'"   # % 보존
    # 방언 더: char(N)→chr, PRAGMA→no-op, 스칼라 MAX/MIN→GREATEST/LEAST, COLLATE NOCASE→LOWER, upsert 기존행 수식
    assert "chr(10)" in translate("SELECT length(replace(text, char(10), ''))")
    assert translate("PRAGMA optimize") == "SELECT 1"
    assert "GREATEST(used_n, 1)" in translate("UPDATE member_memory SET used_n=MAX(used_n, 1) WHERE id=?")
    assert "LEAST(" in translate("SELECT MIN(a, b) FROM t")
    assert translate("SELECT 1 FROM x WHERE u.username=? COLLATE NOCASE") == "SELECT 1 FROM x WHERE LOWER(u.username)=LOWER(%s)"
    assert "SUM((ts>=%s)::int)" in translate("SELECT SUM(ts>=?) FROM x")       # 불리언 합 → ::int
    assert "SUM(points)" in translate("SELECT SUM(points) FROM x")             # 집계 col 은 그대로
    assert "GENERATED BY DEFAULT AS IDENTITY" in translate("CREATE TABLE t(id INTEGER PRIMARY KEY)")  # AUTOINCREMENT 없이도
    assert "GENERATED" not in translate("CREATE TABLE t(a INTEGER NOT NULL, b INTEGER, PRIMARY KEY(a,b))")  # 복합 PK 는 X
    # 문자열 리터럴 안의 ? 는 글자(placeholder 아님), instr→strpos
    assert translate("SELECT COALESCE(x,'?') AS n WHERE id=?") == "SELECT COALESCE(x,'?') AS n WHERE id=%s"
    assert "strpos(" in translate("SELECT substr(r, instr(r, ':')+1) FROM x")


