@test
async def on_conflict_update_qualifies_existing_row_columns():
    """ON CONFLICT DO UPDATE SET 의 기존행 컬럼(증가형·함수 안 bare)이 PG 에서 모호하지 않게 수식되나.
    돈 쿼리: counters n=n+… · subscriptions paid_until=GREATEST(?,COALESCE(paid_until,0),…)."""
    c = _conn()
    if c is None:
        print("  (PG 없음 — 건너뜀)")
        return
    try:
        await c.executescript(
            "DROP TABLE IF EXISTS pgt_c; DROP TABLE IF EXISTS pgt_s;"
            "CREATE TABLE pgt_c(day TEXT, k TEXT, n BIGINT, PRIMARY KEY(day,k));"
            "CREATE TABLE pgt_s(chat_id BIGINT PRIMARY KEY, paid_until BIGINT, trial_until BIGINT);")
        # ① 증가형: n=n+excluded.n (기존행 n 모호) — 두 번 넣으면 합산
        for d in (5, 7):
            await c.execute("INSERT INTO pgt_c(day,k,n) VALUES(?,?,?) ON CONFLICT(day,k) DO UPDATE SET n=n+excluded.n",
                            ("d", "x", d))
        await c.commit()
        assert (await c.execute_fetchall("SELECT n FROM pgt_c WHERE day='d' AND k='x'"))[0]["n"] == 12
        # ② 함수 안 bare 컬럼: paid_until=GREATEST(?, COALESCE(paid_until,0), COALESCE(trial_until,0)) + ?
        sql = ("INSERT INTO pgt_s(chat_id,paid_until,trial_until) VALUES(?,?,?) ON CONFLICT(chat_id) "
               "DO UPDATE SET paid_until = MAX(?, COALESCE(paid_until,0), COALESCE(trial_until,0)) + ?")
        await c.execute(sql, (-1, 100, 50, 0, 0))       # 새 행 → paid_until=100
        await c.execute(sql, (-1, 0, 0, 30, 1000))      # 기존 max(30,100,0)=100 +1000 = 1100
        await c.commit()
        assert (await c.execute_fetchall("SELECT paid_until FROM pgt_s WHERE chat_id=-1"))[0]["paid_until"] == 1100
        await c.executescript("DROP TABLE pgt_c; DROP TABLE pgt_s;")
        await c.commit()
    finally:
        await c.close()


@test
async def pgvector_semsearch_path_on_pg():
    """semsearch._table·_veclit·KNN 쿼리가 PG(pgvector)에서 동작하나 (sqlite-vec 대체). OpenAI 없이 SQL 층만."""
    pre = _conn()
    if pre is None:
        print("  (PG 없음 — 건너뜀)")
        return
    dsn = os.getenv("PG_TEST_DSN") or "dbname=sodam_probe"
    await pre.executescript("DROP SCHEMA public CASCADE; CREATE SCHEMA public;")
    await pre._run(lambda: pre._pg.cursor().execute("CREATE EXTENSION IF NOT EXISTS vector"))
    await pre.commit()
    await pre.close()

    import sodam.handlers  # noqa: F401
    from sodam import semsearch
    from sodam.db import DB
    old = os.environ.get("DB_BACKEND")
    os.environ["DB_BACKEND"] = "pg"
    os.environ["PG_DSN"] = dsn
    db = DB("unused")
    try:
        await db.open()
        assert db.vec is True   # _open_pg 가 pgvector 켬
        await semsearch._table(db)

        def vec(a, b):   # 2D 방향 벡터(나머지 0) → 각도로 거리 조절
            return semsearch._veclit(db, [a, b] + [0.0] * (semsearch.DIM - 2))
        q = vec(1.0, 0.0)
        # 질문에 가까운 순서대로 id 1<2<3 … 넣되, 넣는 순서는 섞어서 (ORDER BY 가 진짜 정렬하는지)
        rows = [(3, vec(0.3, 0.95)), (1, vec(1.0, 0.03)), (6, vec(-1.0, 0.1)),
                (2, vec(0.8, 0.6)), (5, vec(-0.5, 0.9)), (4, vec(0.0, 1.0))]
        await db.atomic(lambda c: c.executemany(
            "INSERT OR REPLACE INTO msg_vec(rowid, chat_id, embedding) VALUES(?,?,?)",
            [(rid, -10, v) for rid, v in rows]))
        # LIMIT 으로 잘리므로 '가까운 3개'(1,2,3)만 나와야 — DESC 로 뒤집으면 먼 것들(6,5,4)이 나와 실패
        near = await db._all("SELECT rowid, (embedding <=> ?) AS distance FROM msg_vec "
                             "WHERE chat_id=? ORDER BY embedding <=> ? LIMIT ?", (q, -10, q, 3))
        ids = [r["rowid"] for r in near]
        assert ids == [1, 2, 3], ids   # 가까운 순, 먼 것(4,5,6) 안 섞임
        assert near[0]["distance"] < near[2]["distance"], [r["distance"] for r in near]
    finally:
        await db.close()
        if old is None:
            os.environ.pop("DB_BACKEND", None)
        else:
            os.environ["DB_BACKEND"] = old
        os.environ.pop("PG_DSN", None)


