def resolve_style(name: str) -> str | None:
    name = name.strip().lower()
    for style in STYLES.values():
        if name == style.key or name in style.aliases:
            return style.key
    return None


def style_list() -> str:
    return " / ".join(s.label for s in STYLES.values())
