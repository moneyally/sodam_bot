# ── SQL 번역: SQLite 방언 → PostgreSQL ──────────────────────────────────
def translate(sql: str) -> str:
    """흔한 SQLite 구문을 PG 로. 자동으로 되는 것만 — 나머지(복잡 strftime·OR REPLACE)는 호출부에서."""
    s = sql
    ignore = bool(re.search(r"\bOR\s+IGNORE\b", s, re.I))
    s = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", s, flags=re.I)
    # 스키마
    # 인라인 단일 INTEGER PRIMARY KEY 는 SQLite 에선 rowid 별칭 = AUTOINCREMENT 유무와 무관하게 자동증가.
    # PG 는 BIGINT GENERATED BY DEFAULT AS IDENTITY (BY DEFAULT: 명시 id 허용 — clone_migrate 가 id 보존 복사·
    # 실제값 PK(chat_id INTEGER PRIMARY KEY)도 그대로 삽입됨. 대량복사 뒤 시퀀스 setval 은 이관 단계). 복합 PK(…)는 미해당.
    s = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?\b",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
    s = re.sub(r"\bAUTOINCREMENT\b", "", s, flags=re.I)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s)          # SQLite INTEGER → PG BIGINT(64bit, telegram id 안전)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)    # SQLite REAL=8바이트 double. PG REAL 은 float4(4바이트)라 유닉스 타임스탬프가 ±128초 반올림돼 expires>=now 비교가 조용히 깨짐 → float8
    # 시각 (흔한 꼴만; '%H'·'%Y-%m-%d' 등은 db.py 통합 때 수동)
    s = re.sub(r"strftime\(\s*'%s'\s*,\s*'now'\s*\)", "extract(epoch from now())::bigint", s, flags=re.I)
    # SQLite char(N)=코드포인트 문자 → PG 는 chr(N) (char 는 PG 에선 타입). DDL 엔 CHAR(N) 타입 안 씀(실측).
    s = re.sub(r"\bchar\(", "chr(", s)
    s = re.sub(r"\binstr\(", "strpos(", s, flags=re.I)   # SQLite instr(hay,needle) = PG strpos(hay,needle) (둘 다 1-based·없으면 0)
    # SQLite json_extract(col, '$.a.b') → PG (col::jsonb #>> '{a,b}') (둘 다 텍스트값, 없으면 NULL)
    s = re.sub(r"\bjson_extract\(\s*([^,]+?)\s*,\s*'\$\.?([^']*)'\s*\)",
               lambda m: f"({m.group(1).strip()}::jsonb #>> '{{{m.group(2).replace('.', ',')}}}')", s, flags=re.I)
    # (ON CONFLICT DO UPDATE SET 의 기존행 bare 컬럼 모호성은 SyncConn._qualify_update 가 introspect 로 처리)
    # PRAGMA (유지보수·open) → PG 엔 없음. 통째 no-op (open 의 PRAGMA 는 _open_pg 가 안 부르지만 optimize 등 유지보수용 대비)
    if re.match(r"\s*PRAGMA\b", s, re.I):
        return "SELECT 1"
    # 스칼라 MAX(a,b,…)/MIN(…) → GREATEST/LEAST (PG MAX/MIN 은 집계 전용·1인자). 괄호 균형으로 top-level 쉼표 있을 때만
    # (중첩 COALESCE(…) 안의 쉼표는 세지 않음 → 집계 MAX(col) 는 안 건드림). 돈 쿼리(구독연장 MAX(?,COALESCE(…),…)) 포함.
    s = _scalar_minmax(s)
    s = _sum_bool(s)   # SUM(불리언) → SUM((…)::int)
    # col = X COLLATE NOCASE (대소문자 무시 비교) → LOWER(col)=LOWER(X). 남은 COLLATE NOCASE 는 떼기(ORDER/색인).
    s = re.sub(r"([\w.]+)\s*=\s*(\S+?)\s+COLLATE\s+NOCASE", r"LOWER(\1)=LOWER(\2)", s, flags=re.I)
    s = re.sub(r"\s+COLLATE\s+NOCASE", "", s, flags=re.I)
    # SQLite IS = null-safe 등호(IS NULL 뿐 아니라 IS '값'·IS ? 도) → PG IS NOT DISTINCT FROM. NULL/TRUE/FALSE/DISTINCT 는 그대로.
    s = re.sub(r"\bIS\s+NOT\s+(?!NULL\b|DISTINCT\b|TRUE\b|FALSE\b)", "IS DISTINCT FROM ", s, flags=re.I)
    s = re.sub(r"\bIS\s+(?!NULL\b|NOT\b|DISTINCT\b|TRUE\b|FALSE\b)", "IS NOT DISTINCT FROM ", s, flags=re.I)
    # SQLite LIKE 는 ASCII 대소문자 무시(코드가 그걸 가정) → PG LIKE 는 대소문자 구분 → 조용히 다른 결과. ILIKE 로 보존.
    # (pg_trgm GIN 은 ILIKE 도 가속. 구조화된 키 LIKE 는 소문자라 과매치 없음.)
    s = re.sub(r"\bNOT\s+LIKE\b", "NOT ILIKE", s, flags=re.I)
    s = re.sub(r"(?<!I)\bLIKE\b", "ILIKE", s, flags=re.I)
    # SQLite LIMIT -1 = 무제한 → PG LIMIT ALL (PG 는 음수 거부)
    s = re.sub(r"\bLIMIT\s+-1\b", "LIMIT ALL", s, flags=re.I)
    # bare 파라미터 ? IS NULL : None 이면 PG 가 타입 못 정함(IndeterminateDatatype) → ?::text IS NULL (NULL 여부만 보니 안전)
    s = re.sub(r"\?\s+IS\s+NULL", "?::text IS NULL", s, flags=re.I)
    # 자리표시자 ? → %s, 리터럴 % → %% (psycopg). 단 **문자열 리터럴 안의 ? 는 글자**(예 COALESCE(x,'?')) → 안 바꿈.
    out, in_str = [], False
    for ch in s:
        if ch == "'":
            in_str = not in_str   # '' (이스케이프 따옴표)는 두 번 토글 = 상태 유지 → OK
            out.append(ch)
        elif ch == "%":
            out.append("%%")      # 리터럴 % → %% (안팎 모두, psycopg 가 되돌림)
        elif ch == "?" and not in_str:
            out.append("%s")
        else:
            out.append(ch)
    s = "".join(out)
    if ignore:
        s = s.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return s


_BOOL_OP = re.compile(r"(>=|<=|!=|<>|>|<|=| AND | OR | NOT | LIKE | IN | IS )", re.I)


def _sum_bool(sql: str) -> str:
    """SQLite 는 SUM(ts>=x) 처럼 불리언을 0/1 로 더함 → PG 는 SUM(boolean) 없음 → SUM((…)::int).
    괄호 균형으로 SUM 인자를 떼서 top-level 에 비교/논리 연산이 있을 때만 감싼다(SUM(col) 는 안 건드림)."""
    out, i = [], 0
    for m in re.finditer(r"\bSUM\(", sql, re.I):
        if m.start() < i:
            continue
        j, depth = m.end(), 1
        while j < len(sql) and depth:
            if sql[j] == "(":
                depth += 1
            elif sql[j] == ")":
                depth -= 1
            j += 1
        inner = sql[m.end():j - 1]                      # SUM( … ) 안쪽
        # 중첩 괄호 밖(top-level)에 비교/논리 연산이 있나
        flat = re.sub(r"\([^()]*\)", "", inner)
        out.append(sql[i:m.end()])
        out.append(f"({inner})::int" if _BOOL_OP.search(flat) else inner)
        out.append(")")
        i = j
    out.append(sql[i:])
    return "".join(out)


def _scalar_minmax(sql: str) -> str:
    """스칼라 MAX(a,b,…)/MIN(…) → GREATEST/LEAST. 괄호 균형으로 top-level 쉼표가 있을 때만 바꾼다
    (집계 MAX(col)·중첩 COALESCE(x,0) 안의 쉼표는 안 셈)."""
    for name, repl in (("MAX", "GREATEST"), ("MIN", "LEAST")):
        out, i = [], 0
        for m in re.finditer(rf"\b{name}\(", sql, re.I):
            if m.start() < i:
                continue
            j, depth, top_comma = m.end(), 1, False
            while j < len(sql) and depth:
                ch = sql[j]
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                elif ch == "," and depth == 1:
                    top_comma = True
                j += 1
            out.append(sql[i:m.start()])
            out.append(repl + "(" if top_comma else sql[m.start():m.end()])   # top-level 쉼표 = 스칼라 → 이름만 교체
            i = m.end()
        out.append(sql[i:])
        sql = "".join(out)
    return sql


_FTS5_RE = re.compile(
    r"CREATE\s+VIRTUAL\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?(\w+)\s+USING\s+fts5\s*\(([^)]*)\)", re.I)


def ddl_for_pg(stmt: str) -> str:
    """스키마(DDL) 한 문장을 PG 로. translate() 가 못 하는 두 가지를 먼저 처리:
      · FTS5 가상표 → 평범한 표(rowid BIGINT PK + 칸 TEXT). `INSERT INTO *_fts(rowid, body)` 코드가 그대로 살고,
        실제 두 글자 검색은 pg_trgm GIN 으로(search.py 통합 때). 실측: 소담 전체 스키마가 이 변환으로 0 실패.
      · COLLATE NOCASE 제거 → 대소문자 무시는 질의에서 lower()/citext 로(통합 때). 색인 생성만 통과시키면 됨.
    """
    m = _FTS5_RE.search(stmt)
    if m:
        cols = ", ".join(c.strip() + " TEXT" for c in m.group(3).split(",") if c.strip())
        return f'CREATE TABLE {m.group(1) or ""}{m.group(2)} (rowid BIGINT PRIMARY KEY, {cols})'
    return translate(re.sub(r"\s+COLLATE\s+NOCASE", "", stmt, flags=re.I))


# ── 행: int 인덱스( row[0] )·키( row["col"] ) 둘 다 되게 (aiosqlite.Row 흉내) ──
class Row:
    __slots__ = ("_vals", "_cols")

    def __init__(self, vals: tuple, cols: tuple[str, ...]):
        self._vals = vals
        self._cols = cols

    def __getitem__(self, k):
        if isinstance(k, int):
            return self._vals[k]
        try:
            return self._vals[self._cols.index(k)]
        except ValueError:                 # 없는 컬럼 → aiosqlite.Row 처럼 IndexError (코드가 except IndexError 로 기본값 처리)
            raise IndexError(k) from None

    def keys(self):
        return list(self._cols)

    def get(self, k, default=None):
        try:
            return self[k]
        except (ValueError, IndexError, KeyError):
            return default

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)


def _row_factory(cursor):
    cols = tuple(d.name for d in cursor.description) if cursor.description else ()

    def make(values):
        return Row(values, cols)
    return make


# ── 커서( c.execute 결과 ) — 전용 스레드에서 미리 뽑은 '값'만 담는다 (스레드 안전) ──
class _Cur:
    __slots__ = ("_rows", "_rowcount", "_last")

    def __init__(self, rows, rowcount, lastrowid):
        self._rows = rows
        self._rowcount = rowcount
        self._last = lastrowid

    def fetchall(self):
        return self._rows

    def fetchone(self):
        return self._rows[0] if self._rows else None

    @property
    def rowcount(self):
        return self._rowcount

    @property
    def lastrowid(self):
        return self._last

    def __iter__(self):           # aiosqlite 커서처럼 직접 순회 가능 (for r in cur)
        return iter(self._rows)


# ── 동기 연결 래퍼 (스레드 안에서만 씀. atomic 콜백이 받는 'c' = db.py 의 self.conn._conn) ──
_REPLACE_RE = re.compile(r"\bINSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I)


def _split_top_commas(s: str) -> list[str]:
    """괄호 밖(top-level) 쉼표로만 쪼갬 (COALESCE(x,0) 안의 쉼표는 안 쪼갬)."""
    out, buf, depth = [], [], 0
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    out.append("".join(buf))
    return out


class SyncConn:
    def __init__(self, pg):
        self._pg = pg
        self._pk: dict[str, list[str]] = {}      # 표별 기본키 컬럼 (INSERT OR REPLACE → ON CONFLICT 용, 캐시)
        self._cols: dict[str, list[str]] = {}    # 표별 전체 컬럼 순서 (컬럼목록 없는 OR REPLACE 용)

    def _pk_cols(self, table: str) -> list[str]:
        if table not in self._pk:
            cur = self._pg.cursor()
            cur.execute("SELECT a.attname FROM pg_index i JOIN pg_attribute a "
                        "ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey) "
                        "WHERE i.indrelid=%s::regclass AND i.indisprimary ORDER BY a.attnum", (table,))
            self._pk[table] = [r[0] for r in cur.fetchall()]
        return self._pk[table]

    def _table_cols(self, table: str) -> list[str]:
        if table not in self._cols:
            cur = self._pg.cursor()
            cur.execute("SELECT column_name FROM information_schema.columns "
                        "WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position", (table,))
            self._cols[table] = [r[0] for r in cur.fetchall()]
        return self._cols[table]

    def _update_or_ignore(self, sql: str, params: tuple):
        """SQLite UPDATE OR IGNORE(충돌 행만 건너뜀) → PG 는 없음. PK introspect 로 '충돌 안 하는 행만' 업데이트
        (행별 skip 재현). 유일한 쓰임 = migrate_chat 의 UPDATE OR IGNORE t SET chat_id=? WHERE chat_id=?."""
        m = re.match(r"\s*UPDATE\s+OR\s+IGNORE\s+(\w+)\s+SET\s+(\w+)\s*=\s*\?(.*)", sql, re.I | re.S)
        if not m:   # 단일 SET=? 꼴 아니면 그냥 OR IGNORE 떼기 (충돌 없으면 동일)
            return re.sub(r"\bUPDATE\s+OR\s+IGNORE\b", "UPDATE", sql, flags=re.I), params
        table, setcol, after = m.group(1), m.group(2), m.group(3)
        others = [c for c in self._pk_cols(table) if c != setcol]
        stripped = f"UPDATE {table} SET {setcol}=?{after}"
        if not others:
            return stripped, params
        cols = ", ".join(others)
        # 바꿀 값(params[0])로 새 PK 가 이미 있는 행은 제외 → 충돌 행만 건너뜀
        guard = f" AND ({cols}) NOT IN (SELECT {cols} FROM {table} WHERE {setcol}=?)"
        return stripped + guard, tuple(params) + (params[0],)

    def _qualify_update(self, sql: str) -> str:
        """ON CONFLICT DO UPDATE SET 의 RHS 에 나오는 '기존행 컬럼'을 표이름으로 수식 (PG 는 EXCLUDED 와 모호).
        표 컬럼을 introspect 해서 bare 컬럼만(앞이 '.'·'excluded.' 아니고 실제 컬럼일 때) table.col 로. LHS(대입 대상)는 그대로."""
        m = re.search(r"\bINSERT\s+INTO\s+(\w+)", sql, re.I)
        mset = re.search(r"\bDO\s+UPDATE\s+SET\b", sql, re.I)
        if not m or not mset:
            return sql
        table = m.group(1)
        cols = set(self._table_cols(table))
        if not cols:
            return sql
        rest = sql[mset.end():]
        mw = re.search(r"\bWHERE\b", rest, re.I)   # ON CONFLICT 의 조건부 WHERE 뒤는 안 건드림(거기도 수식 필요하면 별개)
        setclause, tail = (rest[:mw.start()], rest[mw.start():]) if mw else (rest, "")
        segs = _split_top_commas(setclause)
        new = []
        for seg in segs:
            eq = seg.find("=")
            if eq < 0:
                new.append(seg)
                continue
            lhs, rhs = seg[:eq + 1], seg[eq + 1:]

            def q(mm):
                w = mm.group(0)
                before = rhs[:mm.start()].rstrip()
                if before.endswith(".") or before.lower().endswith("excluded"):
                    return w
                return f"{table}.{w}" if w in cols else w
            new.append(lhs + re.sub(r"\b[A-Za-z_]\w*\b", q, rhs))
        return sql[:mset.end()] + ",".join(new) + tail

    def _replace_to_upsert(self, sql: str) -> str:
        """INSERT OR REPLACE INTO t(cols) VALUES(…) → INSERT … ON CONFLICT(pk) DO UPDATE SET 비-pk=EXCLUDED.…
        표의 기본키를 PG 카탈로그에서 뽑아 자동 변환 (표마다 하드코딩 X — 새 표도 자동)."""
        m = _REPLACE_RE.search(sql)
        if not m:
            return sql
        table = m.group(1)
        explicit = [c.strip() for c in m.group(3).split(",")] if m.group(3) else None
        pk = self._pk_cols(table)
        cols = explicit if explicit is not None else self._table_cols(table)
        # 끝의 \s* 가 VALUES 앞 공백을 먹으므로 뒤에 공백 하나 (pgt_pVALUES 방지)
        new = _REPLACE_RE.sub(lambda mm: "INSERT INTO " + mm.group(1) + (mm.group(2) or "") + " ", sql, count=1)
        if not pk:
            return new   # 기본키 없으면 그냥 INSERT (이 표들엔 없음 — 드묾)
        nonpk = [c for c in cols if c not in pk]
        if nonpk:
            setc = ", ".join(f"{c}=EXCLUDED.{c}" for c in nonpk)
            tail = f" ON CONFLICT ({', '.join(pk)}) DO UPDATE SET {setc}"
        else:
            tail = f" ON CONFLICT ({', '.join(pk)}) DO NOTHING"   # 전부 키면 바꿀 게 없음
        return new.rstrip().rstrip(";") + tail

    def execute(self, sql: str, params: tuple = ()):
        is_insert = bool(re.match(r"\s*INSERT", sql, re.I))
        if is_insert and _REPLACE_RE.search(sql):
            sql = self._replace_to_upsert(sql)
        if is_insert and re.search(r"DO\s+UPDATE\s+SET", sql, re.I):
            sql = self._qualify_update(sql)
        if re.match(r"\s*UPDATE\s+OR\s+IGNORE", sql, re.I):
            sql, params = self._update_or_ignore(sql, tuple(params))
        cur = self._pg.cursor()
        cur.row_factory = _row_factory
        try:
            cur.execute(translate(sql), tuple(params))
        except BaseException as e:   # psycopg 예외 → sqlite3 (코드의 except sqlite3.* 가 작동)
            raise (_as_sqlite_error(e) or e) from e
        rows = cur.fetchall() if cur.description else []
        rowcount = cur.rowcount
        last = None
        if is_insert:
            # lastrowid 흉내: 시퀀스 없는 표면 lastval() 이 에러 → savepoint 로 격리(트랜잭션 전체 오염 방지)
            try:
                with self._pg.transaction():
                    c2 = self._pg.cursor()
                    c2.execute("SELECT lastval()")
                    last = c2.fetchone()[0]
            except Exception:
                last = None
        return _Cur(rows, rowcount, last)

    def executemany(self, sql: str, rows):
        if _REPLACE_RE.search(sql):
            sql = self._replace_to_upsert(sql)
        if re.match(r"\s*INSERT", sql, re.I) and re.search(r"DO\s+UPDATE\s+SET", sql, re.I):
            sql = self._qualify_update(sql)
        cur = self._pg.cursor()
        try:
            cur.executemany(translate(sql), [tuple(r) for r in rows])
        except BaseException as e:
            raise (_as_sqlite_error(e) or e) from e
        return _Cur([], cur.rowcount, None)

    def executescript(self, script: str):
        # 스키마 전용 경로 — FTS5 가상표·COLLATE NOCASE 까지 처리(ddl_for_pg). db.py 는 SCHEMA/EXTRA_SCHEMA 만 이걸 씀.
        for stmt in _split_statements(script):
            if stmt.strip():
                try:
                    self._pg.cursor().execute(ddl_for_pg(stmt))
                except BaseException as e:
                    raise (_as_sqlite_error(e) or e) from e

    def commit(self):
        self._pg.commit()

    def rollback(self):
        self._pg.rollback()


def _as_sqlite_error(e: BaseException):
    """psycopg 예외 → 대응하는 sqlite3 예외 (코드 곳곳의 `except sqlite3.IntegrityError/OperationalError/Error` 가 그대로 작동).
    sqlite3 는 문장 하나 실패해도 연결이 멀쩡하지만 PG 는 트랜잭션이 중단되므로, 부른 쪽에서 롤백도 해야 함(아래 _run_stmt)."""
    import sqlite3
    import psycopg
    if isinstance(e, psycopg.IntegrityError):      # UniqueViolation·ForeignKeyViolation·NotNull·Check …
        return sqlite3.IntegrityError(str(e))
    if isinstance(e, psycopg.OperationalError):
        return sqlite3.OperationalError(str(e))
    if isinstance(e, psycopg.Error):
        return sqlite3.DatabaseError(str(e))
    return None


def _split_statements(script: str) -> list[str]:
    """세미콜론 분리 (따옴표 안 ; 는 보존)."""
    out, buf, q = [], [], None
    for ch in script:
        if q:
            buf.append(ch)
            if ch == q:
                q = None
        elif ch in "'\"":
            q = ch
            buf.append(ch)
        elif ch == ";":
            out.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    if "".join(buf).strip():
        out.append("".join(buf))
    return out


# ── 비동기 연결 (db.py 의 self.conn 자리. 전용 스레드 1개에 고정) ──────────
class PgConnection:
    def __init__(self, dsn: str):
        import psycopg
        self._pool = ThreadPoolExecutor(max_workers=1, thread_name_prefix="pgdb")
        self._dsn = dsn
        # 연결도 그 스레드에서 (psycopg 연결은 만든 스레드에서만 만져야 안전)
        self._pg = self._pool.submit(lambda: psycopg.connect(dsn, autocommit=False)).result()
        self._sync = SyncConn(self._pg)
        self.row_factory = None        # db.py 가 aiosqlite.Row 로 세팅하지만 PG 는 _row_factory 로 이미 처리
        self._thread = None            # db.stop_sync 가 getattr(conn, "_thread", None) 로 봄 (None → join 안 함)

    async def _run(self, fn: Callable[[], Any]):
        loop = asyncio.get_event_loop()
        return await loop.run_in_executor(self._pool, fn)

    async def _run_stmt(self, fn: Callable[[], Any]):
        """단독 문장(_write·_all 등): 에러면 롤백(PG 는 에러가 트랜잭션 전체 중단 → 다음 쿼리까지 막힘, SQLite 는 안 그럼).
        예외 변환(psycopg→sqlite3)은 SyncConn 이 함. atomic 경로(_execute)는 제외 — db.atomic 이 SAVEPOINT 로 스스로 회복."""
        def wrapped():
            try:
                return fn()
            except BaseException:
                try:
                    self._pg.rollback()   # 중단된 트랜잭션 회복 (이 문장만 날아감 — 이전 _write 는 이미 commit)
                except Exception:
                    pass
                raise
        return await self._run(wrapped)

    # ── aiosqlite 내부 흉내: db.py 의 atomic() 이 self.conn._execute(run, self.conn._conn) 로 씀 ──
    @property
    def _conn(self):
        return self._sync

    async def _execute(self, fn: Callable[..., Any], *args):
        """콜백 fn(*args) 를 전용 스레드에서 실행 (aiosqlite.Connection._execute 와 같은 역할)."""
        return await self._run(lambda: fn(*args))

    # ── 공개 API (db.py 의 _all/_one/_write·open 이 씀) ──
    async def execute_fetchall(self, sql: str, params: tuple = ()):
        return await self._run_stmt(lambda: self._sync.execute(sql, params).fetchall())

    async def execute(self, sql: str, params: tuple = ()):
        return await self._run_stmt(lambda: self._sync.execute(sql, params))

    async def executemany(self, sql: str, rows):
        rows = list(rows)
        return await self._run_stmt(lambda: self._sync.executemany(sql, rows))

    async def executescript(self, script: str):
        return await self._run_stmt(lambda: self._sync.executescript(script))

    async def commit(self):
        return await self._run(self._pg.commit)

    async def rollback(self):
        return await self._run(self._pg.rollback)

    async def atomic(self, fn: Callable[[SyncConn], Any]):
        """db.atomic 의 PG 판(테스트·직접호출용). db.py 는 자기 atomic() 을 _execute/_conn 로 돌리므로
        이쪽이 아니라 SAVEPOINT 경로를 탄다 — 둘 다 '전부/전무' 로 같다."""
        def run():
            try:
                r = fn(self._sync)
                self._pg.commit()
                return r
            except BaseException:
                self._pg.rollback()
                raise
        return await self._run(run)

    async def dump_to(self, path: str) -> None:
        """온라인 백업: pg_dump 로 일관된 평문 SQL 덤프 (SQLite conn.backup 의 PG 판).
        pg_dump 는 자기 연결에서 repeatable-read 스냅샷으로 떠서 봇이 돌아가는 중에도 일관됨 → 전용 스레드(DB 연결) 안 묶음."""
        import re
        import subprocess
        args = ["pg_dump", "-d", self._dsn, "-f", path, "--no-owner", "--no-privileges"]
        m = re.search(r"-csearch_path=([^,\s]+)", self._dsn)   # 테스트 하네스: 그 스키마만 (production dsn 엔 없음 → DB 전체)
        if m:
            args += ["-n", m.group(1)]

        def run():
            p = subprocess.run(args, capture_output=True, text=True)
            if p.returncode != 0:
                raise RuntimeError(f"pg_dump 실패(rc={p.returncode}): {(p.stderr or '').strip()[:300]}")
        loop = asyncio.get_event_loop()
        await loop.run_in_executor(None, run)

    async def close(self):
        await self._run(self._pg.close)
        self._pool.shutdown(wait=True)

    def stop(self):
        """이벤트 루프가 끝난 뒤(Ctrl+C) 쓰는 동기 종료. db.stop_sync 가 부름."""
        try:
            self._pg.close()
        except Exception:
            pass
        self._pool.shutdown(wait=False)

